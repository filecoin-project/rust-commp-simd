#!/usr/bin/perl
# gas2plan9.pl — convert ARM64 GAS .S to Plan 9 .s skeleton
#
# Usage:  perl gas2plan9.pl input.S > output.s
#         perl gas2plan9.pl input.S output.s
#
# Two-pass architecture:
#   Pass 1 (preprocess): expand macros inline, resolve .req aliases,
#          strip #ifdef blocks, strip directives → flat instruction stream
#   Pass 2 (convert):    line-by-line GAS → Plan 9 syntax
#
# After running, fill in WORD encodings: asm2plan9s output.s
# Grep for TODO: items needing manual attention

use strict;
use warnings;

my %NEON = map { $_ => 1 } qw(
    ld1 st1 ext shl ushr orr eor and bic movi tbl ins dup
    trn1 trn2 uzp1 uzp2 zip1 zip2 rev32 rev16
    sha256h sha256h2 sha256su0 sha256su1
    addv fmov umov smov cnt neg mvn orn
);

my $infile = shift @ARGV or die "Usage: $0 input.S [output.s]\n";
my $outfile = shift @ARGV;
open(my $fh, '<', $infile) or die "Cannot open $infile: $!\n";
my @raw = <$fh>;
close $fh;

# ═══════════════════════════════════════════════════════
# PASS 1: PREPROCESS → flat instruction stream
# ═══════════════════════════════════════════════════════

# 1a. Collect register aliases
my %alias;
for (@raw) {
    if (/^\s+(\w+)\s+\.req\s+((?:x|w|v|q|s|d)\d+)/) {
        $alias{$1} = $2;
    }
    if (/declare_v\w+\s+(\w+),\s*(\d+)/) {
        $alias{"${1}_v"} = "v$2";
        $alias{"${1}_q"} = "q$2";
        $alias{"${1}_s"} = "s$2";
    }
}

# 1b. Collect macro definitions
my %macro;
{
    my ($in, $name, @params, @body) = (0);
    for (@raw) {
        chomp;
        if (/^\.macro\s+(\w+)(.*)/) {
            $name = $1; my $pstr = $2 // ''; @params = (); @body = ();
            while ($pstr =~ /(\w+)(?::req)?/g) { push @params, $1 }
            $in = 1; next;
        }
        if (/^\.endm/) {
            $macro{$name} = { params => [@params], body => [@body] };
            $in = 0; next;
        }
        push @body, $_ if $in;
    }
}

# 1c. Build flat stream: expand macros, strip platform gunk
my @flat;
{
    my $skip_if = 0;
    my $in_macro = 0;

    for my $line (@raw) {
        chomp $line;

        # #ifdef __APPLE__ / #ifndef __APPLE__ blocks
        if ($line =~ /^#if(?:n?)def\s+__APPLE__/) { $skip_if++; next }
        if ($skip_if > 0) { $skip_if-- if $line =~ /^#endif/; next }
        next if $line =~ /^#(else|define)\b/;

        # Skip macro definition bodies
        if ($line =~ /^\.macro\b/)  { $in_macro = 1; next }
        if ($line =~ /^\.endm/)     { $in_macro = 0; next }
        next if $in_macro;

        # Directives to strip
        next if $line =~ /^\s*\.(text|p2align|align|type|size|arch)\b/;
        next if $line =~ /^\s*SIZE\(/;
        next if $line =~ /^\s*\.req\b/;
        next if $line =~ /declare_v(?:r|ar_vector_reg)\b/;
        # .req lines that survived alias resolution (e.g., "x5 .req x5")
        next if $line =~ /\w+\s+\.req\s+\w/;
        next if $line =~ /^\s*\.globl\b/;

        # GLBL/ENTRY → ##FUNC marker
        if ($line =~ /^GLBL\((\w+)\)/)  { push @flat, "##FUNC $1"; next }
        if ($line =~ /^ENTRY\(/)        { next }

        # Bare function label (e.g., sha256 file uses _func: directly)
        # Only if not a constant label (.quad follows)
        if ($line =~ /^_?(\w+):$/) {
            push @flat, "##LABEL $1";
            next;
        }

        # ADRP+ADD macro pairs → ##ADRP marker
        if ($line =~ /^\s+ADRP_(\w+)\((\w+)\)/) { push @flat, "##ADRP $2 $1"; next }
        if ($line =~ /^\s+ADD_(\w+)\(/)          { next }

        # Macro invocation → expand inline
        if ($line =~ /^\s+(\w+)\b(.*)/ && exists $macro{$1}) {
            push @flat, expand_macro($1, $2, 0);
            next;
        }

        push @flat, $line;
    }
}

# 1d. Resolve all aliases in the flat stream
for my $line (@flat) {
    next if $line =~ /^##/;
    next if $line =~ /^\s*$/;
    next if $line =~ /^[\/*]/;
    $line = resolve_aliases($line);
}

# ═══════════════════════════════════════════════════════
# PASS 2: CONVERT flat GAS → Plan 9
# ═══════════════════════════════════════════════════════

my @out;
push @out, "// Auto-generated by gas2plan9.pl from $infile\n";
push @out, "// Run: asm2plan9s <this_file>\n";
push @out, "// Grep for TODO\n\n";
push @out, "#include \"textflag.h\"\n\n";
push @out, "// ─── Register aliases ───\n";
for (sort keys %alias) { push @out, "// $_ = $alias{$_}\n" }
push @out, "\n";

my @const_vals;
my $const_label = '';

for my $line (@flat) {

    # Our markers
    if ($line =~ /^##FUNC (.+)/) {
        push @out, "\n// TODO: function entry\n";
        push @out, "// TEXT ·$1(SB), NOSPLIT, \$0-NN\n";
        push @out, "//     MOVD arg1+0(FP), R0\n";
        push @out, "//     MOVD arg2+8(FP), R1\n\n";
        next;
    }
    if ($line =~ /^##LABEL (.+)/) {
        flush_const(\@out, $const_label, \@const_vals) if @const_vals;
        $const_label = $1;
        next;
    }
    if ($line =~ /^##ADRP (\w+)\s*(\w*)/) {
        my $lbl = $2 ? "LS_$2" : "LABEL";
        push @out, "\t// TODO: MOVD \$${lbl}<>(SB), " . gp($1) . "\n";
        next;
    }

    # Blank
    if ($line =~ /^\s*$/) { push @out, "\n"; next }

    # Comments
    if ($line =~ /^\s*\/\*[=\-\s]*(.*?)\s*[=\-]*\*\/\s*$/) {
        push @out, "// $1\n" if $1 ne '';
        next;
    }
    if ($line =~ /^\s*\/\*\*?\s?(.*)/) {
        (my $c = $line) =~ s|^\s*/\*\*?\s?|// |;
        $c =~ s|\s*\*/\s*$||;
        push @out, "$c\n";
        next;
    }
    next if $line =~ /^\s*\*\//;
    if ($line =~ /^\s*\*\s?(.*)/) { push @out, "// $1\n"; next }

    # .section rodata marker
    if ($line =~ /^\s*\.section/) { push @out, "\n// ─── Constant data ───\n"; next }

    # .quad/.word/.byte → collect with size
    if ($line =~ /^\s*\.(quad|word|byte)\s+(.+)/) {
        my $size = $1 eq 'quad' ? 8 : $1 eq 'word' ? 4 : 1;
        my $vals_str = $2;
        $vals_str =~ s/\s*\/\*.*?\*\///g;  # strip inline comments
        for my $v (split /\s*,\s*/, $vals_str) {
            $v =~ s/^\s+//; $v =~ s/\s+$//;
            next if $v eq '';
            push @const_vals, [$v, $size];
        }
        next;
    }

    # Labels: .Lfoo → foo
    if ($line =~ /^\.L(\w+):/) { push @out, "$1:\n"; next }

    # Instructions
    push @out, convert($line) . "\n";
}

# Flush trailing constants
flush_const(\@out, $const_label, \@const_vals) if @const_vals;

# ═══════════════════════════════════════════════════════
# OUTPUT
# ═══════════════════════════════════════════════════════

my $result = join('', @out);
$result =~ s/\n{3,}/\n\n/g;

if (defined $outfile) {
    open(my $oh, '>', $outfile) or die "Cannot write $outfile: $!\n";
    print $oh $result;
    close $oh;
    warn "Wrote $outfile\n";
} else {
    print $result;
}

# ═══════════════════════════════════════════════════════
# SUBROUTINES
# ═══════════════════════════════════════════════════════

sub expand_macro {
    my ($name, $args_str, $depth) = @_;
    return ("// ERROR: recursion limit") if $depth > 10;

    my @params = @{$macro{$name}{params}};
    my @body   = @{$macro{$name}{body}};

    $args_str =~ s/^\s+//;  $args_str =~ s/\s+$//;
    my @args = $args_str ne '' ? split(/\s*,\s*/, $args_str) : ();

    my @result;
    for my $raw (@body) {
        my $line = $raw;

        # Substitute parameters
        for my $i (0 .. $#params) {
            my ($p, $v) = ($params[$i], $args[$i] // '');
            $line =~ s/\\${p}\\?\(\)/$v/g;
            $line =~ s/\\${p}\b/$v/g;
        }

        $line =~ s/\s*\/\*.*?\*\///g;   # strip inline comments
        $line =~ s/^\s+//;
        next if $line eq '';
        next if $line =~ /^\/\*/;

        # ADRP_*/ADD_* preprocessor macros (inside GAS .macro bodies)
        if ($line =~ /^ADRP_(\w+)\((\w+)\)/) {
            my $reg = resolve_aliases($2);
            push @result, "##ADRP $reg $1";
            next;
        }
        next if $line =~ /^ADD_(\w+)\(/;

        # Nested macro
        if ($line =~ /^(\w+)\b(.*)/ && exists $macro{$1}) {
            push @result, expand_macro($1, $2, $depth + 1);
            next;
        }

        # Resolve aliases now (concrete register names)
        $line = resolve_aliases("    $line");
        push @result, $line;
    }
    return @result;
}

sub resolve_aliases {
    my ($line) = @_;
    for my $a (sort { length($b) <=> length($a) } keys %alias) {
        $line =~ s/\b$a\b/$alias{$a}/g;
    }
    return $line;
}

sub gp {
    my ($r) = @_;
    $r = $alias{$r} if exists $alias{$r};
    $r =~ s/^x(\d+)$/R$1/;
    $r =~ s/^w(\d+)$/R$1/;
    $r =~ s/^sp$/RSP/;
    return $r;
}

sub is_neon {
    my ($mn, $ops) = @_;
    return 1 if exists $NEON{$mn};
    return 1 if $ops =~ /\bv\d+\.\d*[sbhwd]/;
    return 1 if $ops =~ /\bq\d+/;
    return 1 if $mn =~ /^(ldr|str|stp|ldp)$/ && $ops =~ /q\d+/;
    return 0;
}

sub convert {
    my ($line) = @_;

    my $c = '';
    $c = $1 if $line =~ s/\s*\/\*\s*(.*?)\s*\*\///;

    $line =~ s/^\s+//;
    return '' if $line eq '';

    return "$1:" if $line =~ /^\.L(\w+):/;

    my ($mn, $ops) = ('', '');
    if    ($line =~ /^([a-z]\w*)\s+(.*)$/) { ($mn, $ops) = ($1, $2) }
    elsif ($line =~ /^([a-z]\w*)$/)         { $mn = $1 }
    else  { return "\t// UNPARSED: $line" }

    $c = $c ? "  // $c" : '';

    return "\tRET" if $mn eq 'ret';

    # NEON → WORD
    return "\tWORD \$0x00000000 // $mn $ops$c" if is_neon($mn, $ops);

    # ── GP ──

    # cbz/cbnz
    return "\t" . uc($mn) . " " . gp($1) . ", $2$c"
        if $mn =~ /^cb(n?)z$/ && $ops =~ /^(\w+),\s*\.L(\w+)$/;

    # branches
    return "\t" . uc($mn) . " $1$c"
        if $mn =~ /^b(ne|eq|gt|ge|lt|le|ls|hi|cc|cs)?$/ && $ops =~ /^\.L(\w+)$/;

    if ($mn eq 'bl') {
        return "\tBL $1$c"               if $ops =~ /^\.L(\w+)$/;
        return "\t// TODO: BL $1$c"      if $ops =~ /^(\w+)$/;
    }

    # ldr/str with post-increment [xN], #off → WORD (Go asm lacks post-index)
    if ($mn =~ /^(ldr|str)$/ && $ops =~ /\[.*\],\s*#/) {
        return "\tWORD \$0x00000000 // $mn $ops$c";
    }

    # add/sub with shifted register (lsl/lsr/asr) → WORD
    if ($mn =~ /^(add|sub)$/ && $ops =~ /,\s*\w+,\s*(lsl|lsr|asr)\s+#/) {
        return "\tWORD \$0x00000000 // $mn $ops$c";
    }

    # subs rd, rn, #imm
    return "\tSUBS \$$3, " . gp($2) . ", " . gp($1) . $c
        if $mn eq 'subs' && $ops =~ /^(\w+),\s*(\w+),\s*#(\d+)$/;

    # add/sub rd, rn, #imm
    if ($mn =~ /^(?:add|sub)$/ && $ops =~ /^(\w+),\s*(\w+),\s*#(\d+)$/) {
        my ($rd, $rn, $imm) = ($1, $2, $3);
        return "\t" . uc($mn) . " \$$imm, " . gp($rn) . ", " . gp($rd) . $c;
    }

    # add/sub rd, rn, rm (GP only)
    if ($mn =~ /^(?:add|sub)$/ && $ops =~ /^(\w+),\s*(\w+),\s*(\w+)$/ && $ops !~ /v\d|q\d|\./) {
        my ($rd, $rn, $rm) = ($1, $2, $3);
        return "\t" . uc($mn) . " " . gp($rm) . ", " . gp($rn) . ", " . gp($rd) . $c;
    }

    # cmp
    return "\tCMP \$$2, " . gp($1) . $c
        if $mn eq 'cmp' && $ops =~ /^(\w+),\s*#(\d+)$/;
    return "\tCMP " . gp($2) . ", " . gp($1) . $c
        if $mn eq 'cmp' && $ops =~ /^(\w+),\s*(\w+)$/;

    # mov GP
    return "\tMOVD " . gp($2) . ", " . gp($1) . $c
        if $mn eq 'mov' && $ops =~ /^(x\d+|sp),\s*(x\d+|sp)$/;
    return "\tMOVD \$$2, " . gp($1) . $c
        if $mn eq 'mov' && $ops =~ /^(x\d+),\s*#?(\d+)$/;
    return "\tMOVW " . gp($2) . ", " . gp($1) . $c
        if $mn eq 'mov' && $ops =~ /^(w\d+),\s*(w\d+)$/;
    return "\tMOVW \$$2, " . gp($1) . $c
        if $mn eq 'mov' && $ops =~ /^(w\d+),\s*#?(\d+)$/;

    # ldr/str xN, [base, #off]
    if ($mn eq 'ldr' && $ops =~ /^(x\d+),\s*\[(\w+)(?:,\s*#?(0x[0-9a-f]+|\d+))?\]$/i) {
        return "\tMOVD " . ($3//'0') . "(" . gp($2) . "), " . gp($1) . $c;
    }
    if ($mn eq 'str' && $ops =~ /^(x\d+),\s*\[(\w+)(?:,\s*#?(0x[0-9a-f]+|\d+))?\]$/i) {
        return "\tMOVD " . gp($1) . ", " . ($3//'0') . "(" . gp($2) . ")$c";
    }
    # ldr/str wN
    if ($mn eq 'ldr' && $ops =~ /^(w\d+),\s*\[(\w+)(?:,\s*#?(0x[0-9a-f]+|\d+))?\]$/i) {
        return "\tMOVW " . ($3//'0') . "(" . gp($2) . "), " . gp($1) . $c;
    }

    # stp/ldp GP → TODO (needs manual Plan 9 equivalent)
    # stp/ldp with d-regs (NEON callee-saved) → WORD
    if ($mn =~ /^(stp|ldp)$/ && $ops =~ /d\d+/) {
        return "\tWORD \$0x00000000 // $mn $ops$c";
    }
    # stp/ldp with pre-index (!) → WORD
    if ($mn =~ /^(stp|ldp)$/ && $ops =~ /!\s*$/) {
        return "\tWORD \$0x00000000 // $mn $ops$c";
    }
    # stp/ldp GP → WORD encode (Plan 9 has no multi-register store/load)
    if ($mn =~ /^(stp|ldp)$/ && $ops =~ /x\d+/) {
        return "\tWORD \$0x00000000 // $mn $ops$c";
    }

    # lsl/lsr/asr
    if ($mn =~ /^(?:lsl|lsr|asr)$/ && $ops =~ /^(\w+),\s*(\w+),\s*#(\d+)$/) {
        my ($rd, $rn, $imm) = ($1, $2, $3);
        return "\t" . uc($mn) . " \$$imm, " . gp($rn) . ", " . gp($rd) . $c;
    }

    # Fallback: v/q refs we missed
    return "\tWORD \$0x00000000 // $mn $ops$c" if $ops =~ /\bv\d+|\bq\d+/;

    return "\t// TODO: $mn $ops$c";
}

sub flush_const {
    my ($out, $label, $vals) = @_;
    return unless @$vals && $label;
    push @$out, "\n";
    my $off = 0;
    for my $entry (@$vals) {
        my ($v, $size) = @$entry;
        push @$out, sprintf("DATA %s<>+0x%02x(SB)/%d, \$%s\n", $label, $off, $size, $v);
        $off += $size;
    }
    push @$out, "GLOBL ${label}<>(SB), (NOPTR+RODATA), \$$off\n";
    @$vals = ();
}